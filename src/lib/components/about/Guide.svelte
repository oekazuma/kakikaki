<section class="card">
  <h2>使い方</h2>
  <ol>
    <li>ホーム上部の <b>あ ひらがな｜ア かたかな｜A えいご</b> で練習することばを切り替えます。</li>
    <li>
      単語カードか「もじから えらぶ」で文字を選びます。文字ごとに <b>なぞる（2 回）→ じぶんで かく → おてほんなし</b> の順に自動で進みます。
    </li>
  </ol>
  <dl>
    <dt>なぞる</dt>
    <dd>黄色い線で書き順を見せたあと、番号のついた丸から線に沿って指を動かします。外れると振動してやり直し。</dd>
    <dt>じぶんで かく</dt>
    <dd>薄いお手本の上を自由に塗ります。指を離しても続きが書け、9 割塗れると 1 画完成。線の正確さで星 1〜3 の採点。</dd>
    <dt>おてほんなし</dt>
    <dd>お手本なしで書き、「できた」か 4 秒待つと何の文字に見えるか判定。合格で金の星。</dd>
    <dt>きく</dt>
    <dd>文字と単語を読み上げます。音声はこのボタンでしか流れません。</dd>
  </dl>
</section>

<section class="card">
  <h2>星・メダル・クイズ</h2>
  <ul>
    <li>
      なぞる 2 回 + じぶんで かく 1
      回で文字クリア（★）。単語の全文字クリアで星、全文字が金の星で王冠がカードに付きます。
    </li>
    <li>ホームのトロフィーのボタンから進捗率とメダルを確認できます。条件を満たした瞬間に練習画面でお知らせします。</li>
    <li>
      クイズは よみ（10 問）と かき（5 問）。単語の文字数で かんたん・ふつう・むずかしい に分かれ、正解数を記録します。
    </li>
    <li>
      ホーム左上の顔のボタンで使う人を切り替えられます（10 人まで）。記録・星・メダル・クイズの正解数は
      人ごと・ことばごとに別々に保存されます。名前とアバター（用意した絵か、端末内の写真）は「だれが
      つかう？」の鉛筆ボタンで変えられます。
    </li>
  </ul>
</section>

