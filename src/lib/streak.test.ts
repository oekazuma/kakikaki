import { describe, it, expect } from 'vitest';
import { streak } from './streak';

describe('streak', () => {
  it('何もなければ 0、今日だけなら 1', () => {
    expect(streak([], '2026-09-14')).toBe(0);
    expect(streak(['2026-09-14'], '2026-09-14')).toBe(1);
  });
  it('昨日まで 3 日続いていれば、今日まだ書いていなくても 3', () => {
    expect(streak(['2026-09-11', '2026-09-12', '2026-09-13'], '2026-09-14')).toBe(3);
    expect(streak(['2026-09-13', '2026-09-12', '2026-09-11', '2026-09-14'], '2026-09-14')).toBe(4);
  });
  it('途切れていれば最近の連続分だけ。重複と月またぎも数える', () => {
    expect(streak(['2026-09-01', '2026-09-02', '2026-09-13', '2026-09-13', '2026-09-14'], '2026-09-14')).toBe(2);
    expect(streak(['2026-08-30', '2026-08-31', '2026-09-01'], '2026-09-01')).toBe(3);
    expect(streak(['2026-09-10'], '2026-09-14')).toBe(0);
  });
});
